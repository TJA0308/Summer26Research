# ── dataset ────────────────────────────────────────────────────────────────────
class ScalogramDataset(Dataset):
    def __init__(self, paths, labels, transform=None):
        self.paths, self.labels, self.transform = paths, labels, transform

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, idx):
        img = Image.open(self.paths[idx]).convert("RGB")
        if self.transform:
            img = self.transform(img)
        return img, self.labels[idx]


class ConditionedScalogramDataset(Dataset):
    """Like ScalogramDataset but also returns one or more conditioning labels
    (e.g. predicted speed and/or predicted doc class) per image, used to
    train/evaluate a ConditionedModel."""
    def __init__(self, paths, labels, cond_labels_list, transform=None):
        self.paths, self.labels = paths, labels
        self.cond_labels_list = cond_labels_list   # list of per-conditioning-var label lists
        self.transform = transform

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, idx):
        img = Image.open(self.paths[idx]).convert("RGB")
        if self.transform:
            img = self.transform(img)
        conds = tuple(c[idx] for c in self.cond_labels_list)
        return (img, self.labels[idx]) + conds


class AddGaussianNoise:
    """Adds N(0, std) noise to a [0,1]-scaled tensor before ImageNet normalisation.

    These "images" are z-scored engineered feature matrices (FFT bins, wavelet
    stats, kurtosis/RMS/crest-factor), not photographs -- RandomHorizontalFlip
    and ColorJitter scramble/distort those numeric features in physically
    meaningless ways. Small additive noise is the closer analogue of real
    sensor/measurement noise and is the augmentation actually used here.
    """
    def __init__(self, std=0.02):
        self.std = std

    def __call__(self, tensor):
        if self.std <= 0:
            return tensor
        return tensor + torch.randn_like(tensor) * self.std


def build_transforms(noise_std=0.02):
    train_tf = transforms.Compose([
        transforms.Resize((224, 224), interpolation=transforms.InterpolationMode.BILINEAR),
        transforms.ToTensor(),
        AddGaussianNoise(noise_std),
        transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
    ])
    val_tf = transforms.Compose([
        transforms.Resize((224, 224), interpolation=transforms.InterpolationMode.BILINEAR),
        transforms.ToTensor(),
        transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
    ])
    return train_tf, val_tf


# ── model factory ──────────────────────────────────────────────────────────────
def build_model(arch: str, num_classes: int, dropout: float = 0.0) -> nn.Module:
    def head(in_features):
        if dropout > 0:
            return nn.Sequential(nn.Dropout(dropout), nn.Linear(in_features, num_classes))
        return nn.Linear(in_features, num_classes)

    if arch == "resnet18":
        m = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)
        m.fc = head(m.fc.in_features)
    elif arch == "resnet50":
        m = models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
        m.fc = head(m.fc.in_features)
    elif arch == "efficientnet_b0":
        m = models.efficientnet_b0(weights=models.EfficientNet_B0_Weights.DEFAULT)
        m.classifier[1] = head(m.classifier[1].in_features)
    elif arch == "convnext_tiny":
        m = models.convnext_tiny(weights=models.ConvNeXt_Tiny_Weights.DEFAULT)
        m.classifier[2] = head(m.classifier[2].in_features)
    else:
        raise ValueError(f"Unknown arch: {arch}")
    return m


class ConditionedModel(nn.Module):
    """Wraps any of the 4 backbones; concatenates one-hot conditioning vectors
    (e.g. predicted speed, and/or predicted doc class) with the pooled image
    features before the final classifier head."""
    def __init__(self, arch: str, num_classes: int, cond_dims: list, dropout: float = 0.0):
        super().__init__()
        self.cond_dims = cond_dims

        if arch == "resnet18":
            base = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)
            feat_dim = base.fc.in_features
            base.fc = nn.Identity()
        elif arch == "resnet50":
            base = models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
            feat_dim = base.fc.in_features
            base.fc = nn.Identity()
        elif arch == "efficientnet_b0":
            base = models.efficientnet_b0(weights=models.EfficientNet_B0_Weights.DEFAULT)
            feat_dim = base.classifier[1].in_features
            base.classifier = nn.Identity()
        elif arch == "convnext_tiny":
            base = models.convnext_tiny(weights=models.ConvNeXt_Tiny_Weights.DEFAULT)
            feat_dim = base.classifier[2].in_features
            base.classifier = nn.Sequential(base.classifier[0], base.classifier[1])  # keep LN2d+Flatten
        else:
            raise ValueError(f"Unknown arch: {arch}")

        self.backbone = base
        in_dim  = feat_dim + sum(cond_dims)
        self.head = (nn.Sequential(nn.Dropout(dropout), nn.Linear(in_dim, num_classes))
                     if dropout > 0 else nn.Linear(in_dim, num_classes))

    def forward(self, img, *cond_labels):
        feats   = self.backbone(img)
        onehots = [F.one_hot(lbl, num_classes=d).float() for lbl, d in zip(cond_labels, self.cond_dims)]
        return self.head(torch.cat([feats] + onehots, dim=1))


# ── data loading ───────────────────────────────────────────────────────────────
def load_split(img_dir: Path, target: str, split_id: str = ""):
    df = pd.read_csv(img_dir / "labels.csv")
    df["label"]  = df.apply(lambda r: label_for(target, r["side"], r["feed"], r.get("ra")), axis=1)

    if split_id in EXP_SPLITS:
        test_runs  = EXP_SPLITS[split_id]["test_runs"]
        all_runs   = df["run_id"].unique().tolist()
        train_runs = [r for r in all_runs if r not in test_runs]
    else:
        spec       = TARGETS[target]
        test_runs  = spec["test_runs"]
        train_runs = spec["train_runs"]

    train_df = df[df["run_id"].isin(train_runs)].reset_index(drop=True)
    test_df  = df[df["run_id"].isin(test_runs)].reset_index(drop=True)

    def to_lists(sub):
        paths   = [img_dir / row.filename for _, row in sub.iterrows()]
        labels  = sub["label"].tolist()
        run_ids = sub["run_id"].tolist()
        return paths, labels, run_ids

    return to_lists(train_df), to_lists(test_df)


def load_conditioning(img_dir: Path, parent_target: str, paths: list, run_tag: str = ""):
    """Loads <parent_target>_pred_<scalo>[_<run_tag>].csv (written by
    predict_conditioning.py) and returns predicted labels aligned to `paths`,
    or None if that file doesn't exist yet."""
    scalo_tag = img_dir.name.replace("scalograms_", "")
    suffix    = f"_{run_tag}" if run_tag else ""
    csv_path  = img_dir / f"{parent_target}_pred_{scalo_tag}{suffix}.csv"
    if not csv_path.exists():
        return None
    df = pd.read_csv(csv_path).set_index("filename")
    return [int(df.loc[Path(p).name, "pred_label"]) for p in paths]


# ── SMOTE ──────────────────────────────────────────────────────────────────────
def load_smote_samples(img_dir: Path, target: str, split_id: str = ""):
    """Loads pre-generated synthetic samples written by smote_generate_param.py
    (smote_<target>[_<split_id>]_labels.csv in img_dir). Returns ([], []) if not generated."""
    suffix   = f"_{split_id}" if split_id else ""
    csv_path = img_dir / f"smote_{target}{suffix}_labels.csv"
    if not csv_path.exists():
        return [], []
    df = pd.read_csv(csv_path)
    if df.empty:
        return [], []
    paths  = [img_dir / fn for fn in df["filename"]]
    labels = df["label"].astype(int).tolist()
    return paths, labels


# ── training / evaluation ──────────────────────────────────────────────────────
def train_epoch(model, loader, criterion, optimizer, device):
    model.train()
    total_loss, correct, n = 0.0, 0, 0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        out  = model(imgs)
        loss = criterion(out, labels)
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * len(labels)
        correct    += (out.argmax(1) == labels).sum().item()
        n          += len(labels)
    return total_loss / n, correct / n


@torch.no_grad()
def eval_epoch(model, loader, criterion, device):
    model.eval()
    total_loss, correct, n = 0.0, 0, 0
    all_preds, all_labels  = [], []
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        out  = model(imgs)
        loss = criterion(out, labels)
        total_loss += loss.item() * len(labels)
        preds = out.argmax(1)
        correct    += (preds == labels).sum().item()
        n          += len(labels)
        all_preds.extend(preds.cpu().tolist())
        all_labels.extend(labels.cpu().tolist())
    return total_loss / n, correct / n, all_preds, all_labels


